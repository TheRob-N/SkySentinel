"""Stamps each firmware build with when it was built, so the page and sscheck.sh can show
exactly which build a board is running (the release number stays the same between
releases). PlatformIO runs this before every build (extra_scripts). It writes a one-line
source file into the build folder (never into src/), so only that file recompiles.
"""
import os
import time

Import("env")  # noqa: F821  (defined when PlatformIO runs this)

stamp = int(time.strftime("%y%m%d%H%M"))   # YYMMDDHHMM, local time: 2611110843
out_dir = os.path.join(env.subst("$BUILD_DIR"), "stamp")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, "build_stamp.cpp")
text = ("// Generated by tools/build_stamp.py. Do not edit.\n#include <stdint.h>\n"
        f"extern const uint32_t ssBuildStamp = {stamp}UL;\n")
old = open(path).read() if os.path.exists(path) else None
if old != text:
    with open(path, "w") as f:
        f.write(text)
env.BuildSources(os.path.join("$BUILD_DIR", "stampobj"), out_dir)  # noqa: F821
