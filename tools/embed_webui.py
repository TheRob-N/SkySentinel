"""Builds the web UI into the firmware: gzips webui/index.html into
src/common/webui_gz.h. PlatformIO runs this before every build (extra_scripts);
it can also be run by hand: python3 tools/embed_webui.py
"""
import gzip
import os
import re

try:
    Import("env")  # noqa: F821  (defined when PlatformIO runs this)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "webui", "index.html")
OUT = os.path.join(ROOT, "src", "common", "webui_gz.h")


def main():
    with open(SRC, "rb") as f:
        html = f.read()
    # The firmware installer only works over USB (Web Serial), never from the board's
    # own Wi-Fi, so the copy built into the firmware leaves it out (~300 KB).
    html = re.sub(rb"<!--FLASHER:START-->.*?<!--FLASHER:END-->", b"", html, flags=re.S)
    # mtime=0 keeps the output identical for identical input (no needless rebuilds)
    data = gzip.compress(html, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    text = (
        "// Generated by tools/embed_webui.py from webui/index.html. Do not edit.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        f"static const size_t kWebUiGzLen = {len(data)};\n"
        "static const uint8_t kWebUiGz[] = {\n" + "\n".join(lines) + "\n};\n"
    )
    old = open(OUT).read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, "w") as f:
            f.write(text)
    print(f"web UI: {len(html)} bytes -> {len(data)} gzipped")


main()
