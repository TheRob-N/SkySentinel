"""Builds lib/sscore/ss_oui_makers.h: the IEEE OUIs (MA-L) of phone and tablet makers,
so a Wi-Fi device using its maker's own address can be named ("Samsung") and counted.

    python3 tools/update_oui_makers.py ieee-oui.txt

Input: the IEEE registry as "OUI<TAB>vendor" lines (arp-scan's ieee-oui.txt, or the
IEEE oui.csv converted). Only exact maker names below are taken: Samsung's memory
division, Huawei's network-gear OUIs and the like are left out on purpose.
"""
import re
import sys

# (key, regex on the IEEE vendor name, Bluetooth SIG company id for the MAKER column, phone/tablet maker?)
MAKERS = [
    ("Apple", r"^Apple, Inc\.?$", 0x004C, True),
    ("Samsung", r"^Samsung Electronics Co\.?,? ?Ltd\.?$", 0x0075, True),
    ("Google", r"^Google,? (Inc\.?|LLC)$", 0x00E0, True),
    ("Motorola", r"^Motorola Mobility", 0x0008, True),
    ("OnePlus", r"^OnePlus", 0x072F, True),
    ("Xiaomi", r"Xiaomi", 0x038F, True),
    ("Huawei", r"^Huawei Device", 0x027D, True),
    ("Honor", r"^Honor Device", 0x09C6, True),
    ("OPPO", r"OPPO MOBILE", 0x079A, True),
    ("vivo", r"^vivo Mobile", 0x0837, True),
    ("Realme", r"^Realme", 0x08A4, True),
    ("Sony", r"^Sony Mobile", 0x012D, True),
    ("HMD (Nokia)", r"^HMD Global", 0x0CC3, True),
    ("Nothing", r"^Nothing Technology", 0x0CCB, True),
    ("Fairphone", r"^Fairphone", 0x10CA, True),
    ("Amazon", r"^Amazon Technologies", 0x0171, False),  # Fire tablets, but also Echo, Fire TV, Ring
]


def main():
    entries = []
    for line in open(sys.argv[1], encoding="utf-8", errors="replace"):
        if line.startswith("#") or "\t" not in line:
            continue
        oui, vendor = line.rstrip("\n").split("\t", 1)
        if not re.fullmatch(r"[0-9A-Fa-f]{6}", oui):
            continue
        for i, (_, pat, _, _) in enumerate(MAKERS):
            if re.search(pat, vendor.strip(), re.I):
                entries.append((int(oui, 16), i + 1))
                break
    entries.sort()
    out = ["// Generated by tools/update_oui_makers.py from the IEEE OUI registry. Don't edit.",
           "#pragma once", "", "#include <stdint.h>", "", "namespace ss {", "namespace ouimakers {", "",
           "struct Maker { const char* name; uint16_t company; bool phone; };",
           "static const Maker kMakers[] = {", '  {"", 0xFFFF, false},']
    out += [f'  {{"{n}", 0x{c:04X}, {"true" if p else "false"}}},' for n, _, c, p in MAKERS]
    out += ["};", "", f"// (OUI << 8) | maker index, sorted. {len(entries)} OUIs.",
            "static const uint32_t kOuis[] = {"]
    vals = [f"0x{(o << 8) | m:08X}" for o, m in entries]
    for i in range(0, len(vals), 8):
        out.append("  " + ", ".join(vals[i:i + 8]) + ",")
    out += ["};", "", "}  // namespace ouimakers", "}  // namespace ss", ""]
    open("lib/sscore/ss_oui_makers.h", "w").write("\n".join(out))
    print(f"{len(entries)} OUIs")


main()
